import child_process from 'child_process';
import fs from 'fs';
import path from 'path';
import { test, expect } from './fixtures';

const cliPath = path.resolve(__dirname, '..', 'cli.js');

test('install-browser --help', async () => {
  const output = child_process.execSync(`node ${cliPath} install-browser --help`, { encoding: 'utf-8' });
  expect(output).toContain('install');
});

test('documented env vars in README are supported by runtime', async () => {
  const readmePath = path.resolve(__dirname, '..', 'README.md');
  const readme = fs.readFileSync(readmePath, 'utf-8');
  const optionsSectionMatch = readme.match(/<!--- Options generated by update-readme\.js -->([\s\S]*?)<!--- End of options generated section -->/);
  expect(optionsSectionMatch).toBeTruthy();

  const optionsSection = optionsSectionMatch![1];
  const documentedEnvVars = [...optionsSection.matchAll(/\*env\* `(PLAYWRIGHT_MCP_[A-Z0-9_]+)(?:=[^`]+)?`/g)].map(m => m[1]);
  expect(documentedEnvVars.length).toBeGreaterThan(0);

  const coreBundle = fs.readFileSync(require.resolve('playwright-core/lib/coreBundle'), 'utf-8');
  const runtimeEnvVars = new Set(coreBundle.match(/\bPLAYWRIGHT_MCP_[A-Z0-9_]+\b/g) || []);
  const unsupported = documentedEnvVars.filter(envVar => !runtimeEnvVars.has(envVar));
  expect(unsupported).toEqual([]);

  expect(optionsSection).toMatch(/\| --no-sandbox \|[^|\r\n]*\*env\* `PLAYWRIGHT_MCP_SANDBOX=false` \|/);

  const { tools } = require('playwright-core/lib/coreBundle');
  const config = await tools.resolveCLIConfigForMCP({}, { PLAYWRIGHT_MCP_SANDBOX: 'false' });
  expect(config.browser.launchOptions.chromiumSandbox).toBe(false);
});
